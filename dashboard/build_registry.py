#!/usr/bin/env python3
"""Write dashboard/registry.js from kpi_registry.json and the sql/ files.

The dashboard reads each KPI's numbers from its sheet tab (`sheet_tab`) and shows its SQL in the (i)
dialog, so both come from the registry. Rerun after adding a KPI or changing a query:

    python3 dashboard/build_registry.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIELDS = ["id", "name", "sheet_tab", "sql_file", "redash_data_source_id", "redash_query_id",
          "direction", "enabled", "extra_columns"]


def main():
    registry = json.loads((ROOT / "kpi_registry.json").read_text())
    kpis = []
    for k in registry["kpis"]:
        entry = {f: k[f] for f in FIELDS if f in k}
        entry["sql"] = (ROOT / k["sql_file"]).read_text().rstrip() + "\n"
        kpis.append(entry)
    out = ROOT / "dashboard" / "registry.js"
    out.write_text(
        "// Generated by dashboard/build_registry.py from kpi_registry.json and sql/. Don't edit by hand.\n"
        "window.KPI_REGISTRY = " + json.dumps(kpis, indent=2, ensure_ascii=False) + ";\n"
    )
    print(f"wrote {out.relative_to(ROOT)}: {len(kpis)} KPIs")


if __name__ == "__main__":
    main()
